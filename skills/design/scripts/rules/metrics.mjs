/**
 * metrics (todo 3, GAP-3) — per-screen inline-handler census + frozen
 * baseline + the metrics-regression rule. Registered with validate.mjs's
 * loadRules() via { id, run }; claims its own flags (todo 2 contract — ZERO
 * loader edits):
 *   --metrics         generate <root>/<metrics.baseline>. When the file is
 *                     absent or byte-stable it is written; when the on-disk
 *                     baseline DIVERGES from the regenerated census this mode
 *                     NEVER overwrites it — it fails through the regression
 *                     below, so --update-metrics stays the ONLY declared
 *                     baseline-update path.
 *   --update-metrics  the ONLY write-over path: regenerate and re-freeze the
 *                     baseline (the diff lands in the commit). Runs green by
 *                     construction (the regenerated census IS the new frozen
 *                     baseline).
 *
 * metrics-regression runs EVERY time the baseline file exists — never
 * flag-gated (plain validate runs are covered too). It regenerates the census
 * in memory and compares with the baseline; any divergence fails citing
 * screen + field/event, e.g.
 *   - metrics-regression: login/01-login.html (screen "login"): onclick: baseline 0 != current 1
 *
 * Counting method (declared verbatim in the baseline's `_method`):
 *   scope    = the screen html files listed by every canvas.json under the
 *              validated root (screens only — components/ and unlisted files
 *              are NOT "telas"); the file is the counting unit (two screens
 *              pointing at one file collapse into one entry).
 *   events   = occurrences of inline handler ATTRIBUTES for EXACTLY the 7
 *              types onclick, oninput, onchange, onkeydown, ondragover,
 *              ondragleave, ondrop — case-insensitive `on<event>\s*=` with no
 *              name character before — inside START TAGS only. HTML comments,
 *              <script>/<style> bodies and text nodes never count. Scope =
 *              `on*` attributes in HTML, NOT addEventListener (§13.2 A.2d).
 *   data-action = occurrences of the `data-action` attribute in start tags.
 *   m-classes   = occurrences of class tokens matching /^m-/ inside quoted
 *              class=/className= attribute values of start tags.
 *   totals   = per-field sums over screens (plus the screen count).
 * Output is fully deterministic (no timestamps, sorted keys) — qa.mjs's
 * 10-run stability (R3) and repeated --metrics runs must be byte-identical.
 * Baseline shape (validate.config.json `metrics.baseline` names the file
 * relative to the validated root):
 *   { "_method": <string>, "screens": { <rel html path>: { "screen", "events",
 *     "data-action", "m-classes" } }, "totals": { "screens", "events",
 *     "data-action", "m-classes" } }
 */
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs'
import { join } from 'node:path'

export const id = 'metrics-regression'
export const flags = ['--metrics', '--update-metrics']

const EVENTS = ['onclick', 'oninput', 'onchange', 'onkeydown', 'ondragover', 'ondragleave', 'ondrop']
const EVENT_RE = /(?<![A-Za-z0-9_-])(onclick|oninput|onchange|onkeydown|ondragover|ondragleave|ondrop)\s*=/gi
const DATA_ACTION_RE = /(?<![A-Za-z0-9_-])data-action\s*=/gi
const CLASS_ATTR_RE = /(?<![A-Za-z0-9_-])(?:className|class)\s*=\s*(?:"([^"]*)"|'([^']*)')/gi
// Start tags only — comments/script/style are consumed wholesale (same
// alternation contract as validate.mjs's TAG_SCAN_RE) so markup text or JS
// strings can never masquerade as handlers.
const TAG_RE = /<!--[\s\S]*?-->|<script\b[^>]*>[\s\S]*?<\/script>|<style\b[^>]*>[\s\S]*?<\/style>|<[a-zA-Z][^>]*>/g
const NON_TAG_RE = /^(?:<!--|<script|<style)/i
const M_CLASS_RE = /^m-/
const MAX_FINDINGS = 10

const METHOD =
  'Per-screen inline-handler census generated by skills/design/scripts/rules/metrics.mjs ' +
  '(validate.mjs rule "metrics-regression"). Scope: the screen html files listed by every ' +
  'canvas.json under the validated root (screens only - components/ and unlisted files are ' +
  'not telas; the file is the counting unit). events: occurrences of inline handler ' +
  'attributes for EXACTLY the 7 types (onclick, oninput, onchange, onkeydown, ondragover, ' +
  'ondragleave, ondrop), case-insensitive match of on<event>= preceded by no name ' +
  'character, inside START TAGS only (HTML comments, <script>/<style> bodies and text ' +
  'nodes never count; scope = on* attributes in HTML, NOT addEventListener). ' +
  'data-action: occurrences of the data-action attribute in start tags. m-classes: ' +
  'occurrences of class tokens matching /^m-/ in quoted class=/className= attribute ' +
  'values. totals: per-field sums over screens. Deterministic: no timestamps, sorted ' +
  'keys, 2-space JSON. The baseline is FROZEN: metrics-regression reruns this census on ' +
  'every validate run and fails on any divergence (screen+event cited); the ONLY ' +
  'declared update path is validate.mjs --update-metrics (the regenerated diff must ' +
  'land in the commit).'

export function run(ctx) {
  const cfg = ctx.config?.metrics
  if (!isPlainObject(cfg) || typeof cfg.baseline !== 'string' || cfg.baseline.length === 0) {
    return ctx.fail('invalid-shape', 'validate.config.json: "metrics.baseline" must be a non-empty string')
  }
  const name = cfg.baseline.replaceAll('\\', '/').replace(/^\.\//, '')
  if (name.startsWith('/') || name.split('/').includes('..')) {
    return ctx.fail('invalid-shape', `validate.config.json: "metrics.baseline" ${JSON.stringify(cfg.baseline)} escapes the validated root`)
  }
  const baselinePath = join(ctx.rootDir, name)
  const doc = buildDoc(ctx)
  const update = ctx.flags.includes('--update-metrics')
  const generate = ctx.flags.includes('--metrics')

  if (update) {
    // The ONLY declared baseline-update path: regenerate and re-freeze.
    writeBaseline(baselinePath, doc)
    console.log(`metrics: baseline updated: ${name} (${doc.totals.screens} screen(s))`)
    return
  }

  const existing = readBaseline(ctx, name, baselinePath) // {absent} | {invalid} | {doc}
  if (generate) {
    if (existing.absent) {
      writeBaseline(baselinePath, doc)
      console.log(`metrics: wrote ${name} (${Object.keys(doc.screens).length} screen(s))`)
      return
    }
    if (existing.doc !== undefined && collectDiffs(existing.doc, doc, name).length === 0) {
      // Byte-stable regeneration (deterministic output proof).
      writeBaseline(baselinePath, doc)
    }
    // Divergent or corrupt: NEVER overwrite — the regression below fails the
    // run and points at --update-metrics (the only update path).
  }

  // metrics-regression: runs whenever the baseline exists — never flag-gated.
  if (existing.absent || existing.doc === undefined) return
  reportDiffs(ctx, collectDiffs(existing.doc, doc, name))
}

// ---------------------------------------------------------------------------
// Census
// ---------------------------------------------------------------------------
function buildDoc(ctx) {
  const screens = {}
  for (const { dir, manifest } of discoverManifests(ctx)) {
    const list = Array.isArray(manifest.screens) ? manifest.screens : []
    for (const screen of list) {
      if (!isPlainObject(screen)) continue
      if (typeof screen.id !== 'string' || typeof screen.file !== 'string' || screen.file.length === 0) continue
      if (escapesRoot(screen.file)) continue
      const full = join(dir, screen.file)
      const key = ctx.relLabel(ctx.rootDir, full)
      if (Object.prototype.hasOwnProperty.call(screens, key)) continue // one entry per file
      screens[key] = { screen: screen.id, ...censusFile(full) }
    }
  }
  const ordered = {}
  for (const key of Object.keys(screens).sort()) ordered[key] = screens[key]
  const totals = { screens: Object.keys(ordered).length, events: zeroEvents(), 'data-action': 0, 'm-classes': 0 }
  for (const entry of Object.values(ordered)) {
    for (const event of EVENTS) totals.events[event] += entry.events[event]
    totals['data-action'] += entry['data-action']
    totals['m-classes'] += entry['m-classes']
  }
  return { _method: METHOD, screens: ordered, totals }
}

function censusFile(full) {
  const out = { events: zeroEvents(), 'data-action': 0, 'm-classes': 0 }
  let html = null
  try {
    html = readFileSync(full, 'utf8')
  } catch {
    return out // unreadable screen file = zero counts (validate reports the file)
  }
  for (const m of html.matchAll(TAG_RE)) {
    const tag = m[0]
    if (NON_TAG_RE.test(tag)) continue // comment/script/style consumed wholesale
    for (const em of tag.matchAll(EVENT_RE)) out.events[em[1].toLowerCase()] += 1
    out['data-action'] += [...tag.matchAll(DATA_ACTION_RE)].length
    for (const cm of tag.matchAll(CLASS_ATTR_RE)) {
      for (const token of (cm[1] ?? cm[2] ?? '').split(/\s+/)) {
        if (token !== '' && M_CLASS_RE.test(token)) out['m-classes'] += 1
      }
    }
  }
  return out
}

function zeroEvents() {
  const events = {}
  for (const event of EVENTS) events[event] = 0
  return events
}

/** Every canvas.json under the validated root (exemptDirs skipped — the
 * snapshots/ copies of manifests are inert). Unparseable manifests are
 * skipped: validate.mjs already reports invalid-json for them. */
function discoverManifests(ctx) {
  const out = []
  const exempt = new Set(
    Array.isArray(ctx.config?.exemptDirs) ? ctx.config.exemptDirs.filter((d) => typeof d === 'string') : [],
  )
  const walk = (dir) => {
    let entries = []
    try {
      entries = readdirSync(dir, { withFileTypes: true })
    } catch {}
    entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    for (const entry of entries) {
      if (entry.isDirectory() && !exempt.has(entry.name)) walk(join(dir, entry.name))
    }
    let manifest = null
    try {
      manifest = JSON.parse(readFileSync(join(dir, 'canvas.json'), 'utf8'))
    } catch {}
    if (isPlainObject(manifest)) out.push({ dir, manifest })
  }
  walk(ctx.rootDir)
  return out
}

function escapesRoot(file) {
  return (
    file.startsWith('/') ||
    file.includes('\\') ||
    /^[a-zA-Z][a-zA-Z0-9+.-]*:/.test(file) ||
    file.split('/').includes('..')
  )
}

// ---------------------------------------------------------------------------
// Baseline I/O + regression diff
// ---------------------------------------------------------------------------
function writeBaseline(path, doc) {
  writeFileSync(path, `${JSON.stringify(doc, null, 2)}\n`, 'utf8')
}

/** {absent} | {invalid} (problems already reported) | {doc} (shape-checked). */
function readBaseline(ctx, name, path) {
  let st = null
  try {
    st = statSync(path)
  } catch {}
  if (!st?.isFile()) return { absent: true }
  let raw = null
  try {
    raw = readFileSync(path, 'utf8')
  } catch {
    ctx.fail('invalid-json', `${name}: unreadable`)
    return { invalid: true }
  }
  let parsed = null
  try {
    parsed = JSON.parse(raw)
  } catch (error) {
    ctx.fail('invalid-json', `${name}: ${String(error?.message ?? error)}`)
    return { invalid: true }
  }
  if (
    !isPlainObject(parsed) ||
    typeof parsed._method !== 'string' ||
    !isPlainObject(parsed.screens) ||
    !isPlainObject(parsed.totals)
  ) {
    ctx.fail('invalid-shape', `${name}: the baseline must be { "_method": <string>, "screens": <object>, "totals": <object> }`)
    return { invalid: true }
  }
  return { doc: parsed }
}

/** Field-wise diff over the DECLARED doc fields; empty list = equal. */
function collectDiffs(baseline, current, name) {
  const diffs = []
  if (baseline._method !== current._method) {
    diffs.push(`${name}: _method: the counting method changed since the baseline was frozen`)
  }
  const baseScreens = baseline.screens
  const curScreens = current.screens
  for (const key of Object.keys(curScreens).sort()) {
    const cur = curScreens[key]
    const base = baseScreens[key]
    if (base === undefined) {
      diffs.push(`${key} (screen "${cur.screen}"): present in the tree but missing from the baseline`)
      continue
    }
    pushEntryDiffs(diffs, key, cur.screen, base, cur)
  }
  for (const key of Object.keys(baseScreens).sort()) {
    if (curScreens[key] === undefined) {
      const base = baseScreens[key]
      const id = isPlainObject(base) && typeof base.screen === 'string' ? base.screen : '?'
      diffs.push(`${key} (screen "${id}"): in the baseline but no longer present in the tree`)
    }
  }
  pushEntryDiffs(diffs, 'totals', null, baseline.totals, current.totals)
  return diffs
}

function pushEntryDiffs(diffs, key, screen, base, cur) {
  const where = screen === null ? key : `${key} (screen "${screen}")`
  const baseEvents = isPlainObject(base) ? base.events : undefined
  const curEvents = isPlainObject(cur) ? cur.events : undefined
  for (const event of EVENTS) {
    const a = isPlainObject(baseEvents) ? baseEvents[event] : undefined
    const b = isPlainObject(curEvents) ? curEvents[event] : undefined
    if (a !== b) diffs.push(`${where}: ${event}: baseline ${a ?? '(absent)'} != current ${b ?? '(absent)'}`)
  }
  for (const field of ['data-action', 'm-classes', 'screens', 'screen']) {
    const a = isPlainObject(base) ? base[field] : undefined
    const b = isPlainObject(cur) ? cur[field] : undefined
    if (a === undefined && b === undefined) continue
    if (a !== b) diffs.push(`${where}: ${field}: baseline ${JSON.stringify(a) ?? '(absent)'} != current ${JSON.stringify(b) ?? '(absent)'}`)
  }
}

function reportDiffs(ctx, diffs) {
  if (diffs.length === 0) return
  let shown = 0
  for (const line of diffs) {
    if (shown < MAX_FINDINGS) {
      shown += 1
      ctx.fail('metrics-regression', line)
    }
  }
  if (diffs.length > MAX_FINDINGS) {
    ctx.fail('metrics-regression', `${diffs.length - MAX_FINDINGS} more divergence(s) suppressed (first ${MAX_FINDINGS} shown)`)
  }
  ctx.fail('metrics-regression', 'run validate.mjs --update-metrics to accept the new baseline (the only declared update path)')
}

function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}
