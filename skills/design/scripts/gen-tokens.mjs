#!/usr/bin/env node
/**
 * gen-tokens.mjs — generate design-system.css from tokens.json (DTCG-ish).
 *
 * Usage:
 *   node gen-tokens.mjs [design-root]   write <design-root>/design-system.css
 *                                       (default design-root: ./design)
 *   node gen-tokens.mjs --list          print utilities vocabulary, one class per line
 *
 * Input contract (tokens.json):
 *   - root sections "light" and "dark" with identical structure
 *   - token groups by type ($type: color|dimension|typography|shadow|borderRadius)
 *   - every token object must carry $value (hex/rgb colors, px dimensions, composites)
 *   - optional root $extensions.designPack.contrastPairs = [{fg, bg, minRatio}, ...]
 *
 * Output contract (design-system.css):
 *   - first line: "GENERATED by gen-tokens.mjs" banner holding tokens-hash: <sha256>
 *     (sha256 over tokens.json bytes with all \r removed)
 *   - [data-theme="light"] and [data-theme="dark"] blocks with --* custom properties
 *   - deterministic: identical input bytes => byte-identical output
 *
 * Exit codes: 0 ok, 2 usage/input error (invalid JSON, token missing $value).
 * Node 18+, stdlib only (node:fs, node:path, node:crypto).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createHash } from "node:crypto";

const THEMES = ["light", "dark"];

/** Initial utilities vocabulary (todo 3 pins the exact matrix + golden). */
const VOCABULARY = [
  "bg-*",
  "text-*",
  "border-*",
  "p-*",
  "m-*",
  "gap-*",
  "rounded-*",
  "font-*",
  "leading-*",
  "shadow-*",
  "w-*",
  "h-*",
  "min-h-*",
  "[data-state]",
];

function fail(message) {
  process.stderr.write(`gen-tokens: ${message}\n`);
  process.exit(2);
}

function kebab(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function isPlainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

/**
 * Turn one token $value into CSS declarations (name: value pairs).
 * - primitives emit one declaration
 * - typography composites flatten into <name>-<kebab(subkey)>
 * - shadow composites compose into a box-shadow shorthand
 * `cssName` is the dash-joined custom-property base; `dotted` is the human token path.
 */
function declarationsFor(cssName, dotted, value, type, themeName) {
  if (Array.isArray(value)) {
    if (type === "shadow") {
      return [[cssName, value.map((s) => shadowShorthand(s, dotted, themeName)).join(", ")]];
    }
    fail(`theme "${themeName}": token "${dotted}" has array $value of unsupported type "${type ?? "?"}"`);
  }
  if (isPlainObject(value)) {
    if (type === "shadow") {
      return [[cssName, shadowShorthand(value, dotted, themeName)]];
    }
    const out = [];
    for (const [key, sub] of Object.entries(value)) {
      if (key.startsWith("$")) continue;
      if (isPlainObject(sub) || Array.isArray(sub)) {
        fail(`theme "${themeName}": token "${dotted}.${key}" must be a primitive $value sub-entry`);
      }
      out.push([`${cssName}-${kebab(key)}`, String(sub)]);
    }
    return out;
  }
  return [[cssName, String(value)]];
}

function shadowShorthand(shadow, name, themeName) {
  if (!isPlainObject(shadow)) {
    fail(`theme "${themeName}": token "${name}" shadow entry must be an object`);
  }
  const offsetX = shadow.offsetX ?? shadow.x;
  const offsetY = shadow.offsetY ?? shadow.y;
  const { blur, spread, color } = shadow;
  if (offsetX === undefined || offsetY === undefined || blur === undefined) {
    fail(`theme "${themeName}": token "${name}" shadow needs offsetX/offsetY/blur (got ${JSON.stringify(shadow)})`);
  }
  return [offsetX, offsetY, blur, spread ?? "0px", color ?? "transparent"].join(" ");
}

/**
 * Walk one theme section into [name, value] declaration pairs.
 * Group objects carry $type; token objects carry $value; anything else = input error.
 */
function collectTheme(themeName, theme) {
  const declarations = [];
  const walk = (node, pathParts) => {
    for (const [key, entry] of Object.entries(node)) {
      if (key.startsWith("$")) continue;
      const parts = [...pathParts, kebab(key)];
      const dotted = parts.join(".");
      const cssName = parts.join("-");
      if (!isPlainObject(entry)) {
        fail(`theme "${themeName}": token "${dotted}" must be an object with $value`);
      }
      if (Object.prototype.hasOwnProperty.call(entry, "$value")) {
        const type = entry.$type ?? node.$type ?? null;
        declarations.push(...declarationsFor(cssName, dotted, entry.$value, type, themeName));
      } else if (typeof entry.$type === "string") {
        walk(entry, parts);
      } else {
        fail(`theme "${themeName}": token "${dotted}" missing $value`);
      }
    }
  };
  for (const [groupName, group] of Object.entries(theme)) {
    if (groupName.startsWith("$")) continue;
    if (!isPlainObject(group)) {
      fail(`theme "${themeName}": group "${groupName}" must be an object`);
    }
    if (typeof group.$type !== "string") {
      fail(`theme "${themeName}": group "${groupName}" missing $type`);
    }
    walk(group, [kebab(groupName)]);
  }
  return declarations;
}

function buildCss(hash, themeDeclarations) {
  const lines = [
    `/* GENERATED by gen-tokens.mjs — do not edit; tokens-hash: ${hash} */`,
    "",
  ];
  for (const themeName of THEMES) {
    lines.push(`[data-theme="${themeName}"] {`);
    for (const [name, value] of themeDeclarations[themeName]) {
      lines.push(`  --${name}: ${value};`);
    }
    lines.push("}");
    lines.push("");
  }
  return lines.join("\n");
}

function main(argv) {
  if (argv.includes("--list")) {
    process.stdout.write(`${VOCABULARY.join("\n")}\n`);
    return 0;
  }
  const positional = argv.filter((a) => !a.startsWith("--"));
  const unknown = argv.filter((a) => a.startsWith("--"));
  if (unknown.length > 0) {
    fail(`unknown flag "${unknown[0]}" — usage: gen-tokens.mjs [design-root] | --list`);
  }
  if (positional.length > 1) {
    fail(`usage: gen-tokens.mjs [design-root] | --list (got ${positional.length} positional args)`);
  }

  const root = resolve(positional[0] ?? "./design");
  const tokensPath = join(root, "tokens.json");
  let raw;
  try {
    raw = readFileSync(tokensPath);
  } catch {
    fail(`cannot read ${tokensPath}`);
  }
  // Windows-safe normalization: hashes must not depend on \r (see plan verification strategy).
  const normalized = raw.toString("utf8").replace(/\r/g, "");
  let tokens;
  try {
    tokens = JSON.parse(normalized);
  } catch (err) {
    fail(`invalid JSON in ${tokensPath}: ${err.message}`);
  }
  if (!isPlainObject(tokens)) {
    fail(`invalid tokens in ${tokensPath}: root must be an object`);
  }
  for (const themeName of THEMES) {
    if (!isPlainObject(tokens[themeName])) {
      fail(`invalid tokens in ${tokensPath}: missing "${themeName}" theme section`);
    }
  }

  const hash = createHash("sha256").update(normalized, "utf8").digest("hex");
  const themeDeclarations = {};
  for (const themeName of THEMES) {
    themeDeclarations[themeName] = collectTheme(themeName, tokens[themeName]);
  }

  const outPath = join(root, "design-system.css");
  writeFileSync(outPath, buildCss(hash, themeDeclarations), "utf8");
  process.stdout.write(`wrote ${outPath}\n`);
  return 0;
}

process.exit(main(process.argv.slice(2)));
