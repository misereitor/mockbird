#!/usr/bin/env node
/* mockbird:config-driven:v2 */
/**
 * gen-tokens.mjs — generate design-system.css from tokens.json (DTCG-ish).
 *
 * Usage:
 *   node gen-tokens.mjs [design-root]   write <design-root>/tokens.json,
 *                                       <design-root>/design-system.css and
 *                                       <design-root>/utilities.css
 *                                       (default design-root: ./design)
 *   node gen-tokens.mjs --list          print the utilities matrix, one entry per line
 *                                       (exact golden list — root-independent)
 *   node gen-tokens.mjs --contract [design-root] [contract-out]
 *                                       the normal run PLUS the generated token
 *                                       contract table (todo 20): a values
 *                                       table derived from the same tree this
 *                                       script writes to tokens.json (single
 *                                       source of truth — values are never
 *                                       hand-maintained). Default output:
 *                                       <design-root>/tokens.contract.md; the
 *                                       optional second positional overrides
 *                                       the output path (the skill pack keeps
 *                                       the artifact at
 *                                       skills/design/assets/tokens.contract.md).
 *                                       Deterministic: identical tokens.json
 *                                       bytes => byte-identical table.
 *
 * Input contract (tokens.json):
 *   - root sections "light" and "dark" with identical structure
 *   - token groups by type ($type: color|dimension|typography|shadow|borderRadius)
 *   - every token object must carry $value (hex/rgb colors, px dimensions, composites)
 *   - optional root $extensions.designPack.contrastPairs = [{fg, bg, minRatio}, ...]
 *
 * Contract groups (todo 19): the groups motion/density/breakpoints/layers are
 * DECLARED in lib/token-groups.mjs with their exact values and written into
 * EVERY theme section of tokens.json on every run (declared values win;
 * missing groups are appended). tokens.json is serialized deterministically
 * (2-space indent, stable key order: source keys in order, then the contract
 * groups in declared order), so the tokens-hash below covers them too —
 * mutating any token value (contract group included) trips validate.mjs
 * staleness.
 *
 * Output contract (design-system.css):
 *   - first line: "GENERATED by gen-tokens.mjs" banner holding tokens-hash: <sha256>
 *     (sha256 over the tokens.json bytes this script writes — the same bytes
 *     validate.mjs hashes with all \r removed)
 *   - [data-theme="light"] and [data-theme="dark"] blocks with --* custom properties
 *   - deterministic: identical input bytes => byte-identical output
 *
 * Output contract (utilities.css):
 *   - SAME first-line "GENERATED by gen-tokens.mjs" banner with the same tokens-hash
 *   - ONLY the static matrix classes (closed vocabulary, ~140 entries):
 *     every color value is var(--…)-based; only non-color literals allowed
 *     (0, px/rem, %, vw/vh, unitless, keywords)
 *   - deterministic: identical input bytes => byte-identical output
 *
 * Output contract (tokens.contract.md, --contract only):
 *   - a markdown values table (| token | light | dark |) over every token of
 *     both theme sections — the contract groups (motion.easing/motion.duration/
 *     density/breakpoints/layers) included — one row per token path, rows in
 *     codepoint order, composite $values as compact JSON
 *   - the SKILL.md embed between <!-- contract:begin --> and
 *     <!-- contract:end --> is byte-identical to this content; the validator
 *     rule rules/contract-doc-sync.mjs regenerates the table in-memory and
 *     diffs both artifacts against it (drift = exit 1 citing the drifted keys)
 *   - deterministic: identical input bytes => byte-identical output
 *
 * Exit codes: 0 ok, 2 usage/input error (invalid JSON, token missing $value,
 * unknown flag, duplicate class in the matrix).
 * Node 18+, stdlib only (node:fs, node:path, node:crypto).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createHash } from "node:crypto";
import { withContractGroups } from "./lib/token-groups.mjs";

const THEMES = ["light", "dark"];

/**
 * Static closed utilities matrix (todo 3): 140 entries = 137 classes +
 * 3 [data-state=…] helpers, in exact golden order (fixtures/ok/utilities-spec.txt).
 * Root-independent: `--list` and utilities.css do not depend on tokens.json content.
 * Missing design tokens simply leave the var(--…) unresolved at runtime (v1).
 */
const COLORS = ["bg", "surface", "text", "muted", "accent", "border"];
const SPACING_FAMILIES = [
  ["p", ["padding"]],
  ["px", ["padding-left", "padding-right"]],
  ["py", ["padding-top", "padding-bottom"]],
  ["pt", ["padding-top"]],
  ["pr", ["padding-right"]],
  ["pb", ["padding-bottom"]],
  ["pl", ["padding-left"]],
  ["m", ["margin"]],
  ["mx", ["margin-left", "margin-right"]],
  ["my", ["margin-top", "margin-bottom"]],
  ["mt", ["margin-top"]],
  ["mr", ["margin-right"]],
  ["mb", ["margin-bottom"]],
  ["ml", ["margin-left"]],
  ["gap", ["gap"]],
  ["gap-x", ["column-gap"]],
  ["gap-y", ["row-gap"]],
];
const STEPS = [0, 1, 2, 3, 4];

function stepValue(n) {
  return n === 0 ? "0" : `var(--dimension-space-${n})`;
}

/** Build the matrix entries [{name, decls}] — `name` is the golden line. */
function buildMatrix() {
  const entries = [];
  const add = (name, decls) => entries.push({ name, decls });
  // A. bg-<color>
  for (const c of COLORS) add(`bg-${c}`, [["background-color", `var(--color-${c})`]]);
  // B. text-<color> (color family; suffixes disjoint from the type family)
  for (const c of COLORS) add(`text-${c}`, [["color", `var(--color-${c})`]]);
  // C. border-<color>
  for (const c of COLORS) add(`border-${c}`, [["border-color", `var(--color-${c})`]]);
  // D. spacing: 17 families × 5 steps = 85
  for (const [family, props] of SPACING_FAMILIES) {
    for (const n of STEPS) {
      const v = stepValue(n);
      add(`${family}-${n}`, props.map((p) => [p, v]));
    }
  }
  // E. sizing: 22
  for (const n of STEPS) add(`w-${n}`, [["width", stepValue(n)]]);
  add("w-full", [["width", "100%"]]);
  add("w-screen", [["width", "100vw"]]);
  add("w-max-width", [["width", "var(--dimension-max-width)"]]);
  for (const n of STEPS) add(`h-${n}`, [["height", stepValue(n)]]);
  add("h-full", [["height", "100%"]]);
  add("h-screen", [["height", "100vh"]]);
  for (const n of STEPS) add(`min-h-${n}`, [["min-height", stepValue(n)]]);
  add("min-h-full", [["min-height", "100%"]]);
  add("min-h-screen", [["min-height", "100vh"]]);
  // F. radii: 3
  for (const r of ["sm", "md", "lg"]) {
    add(`rounded-${r}`, [["border-radius", `var(--border-radius-${r})`]]);
  }
  // G. type scale: 8 (font-normal/font-bold alias the typography token carrying
  //    that weight in matrix order: body → normal, heading → bold)
  add("font-body", [["font-family", "var(--typography-body-font-family)"]]);
  add("font-heading", [["font-family", "var(--typography-heading-font-family)"]]);
  add("text-body", [["font-size", "var(--typography-body-font-size)"]]);
  add("text-heading", [["font-size", "var(--typography-heading-font-size)"]]);
  add("leading-body", [["line-height", "var(--typography-body-line-height)"]]);
  add("leading-heading", [["line-height", "var(--typography-heading-line-height)"]]);
  add("font-normal", [["font-weight", "var(--typography-body-font-weight)"]]);
  add("font-bold", [["font-weight", "var(--typography-heading-font-weight)"]]);
  // H. shadows: 1
  add("shadow-card", [["box-shadow", "var(--shadow-card)"]]);
  // I. state helpers: 3 (attribute selectors — the golden lines are the selectors)
  add('[data-state="hover"]', [["background-color", "var(--color-surface)"]]);
  add('[data-state="active"]', [["background-color", "var(--color-border)"]]);
  add('[data-state="disabled"]', [["opacity", "0.5"], ["cursor", "not-allowed"], ["pointer-events", "none"]]);
  // Duplicate class name during build → input/contract error (exit 2).
  const seen = new Set();
  for (const { name } of entries) {
    if (seen.has(name)) {
      fail(`duplicate class "${name}" in the utilities matrix`);
    }
    seen.add(name);
  }
  return entries;
}

function generatedHeader(hash) {
  return `/* GENERATED by gen-tokens.mjs — do not edit; tokens-hash: ${hash} */`;
}

function fail(message) {
  process.stderr.write(`gen-tokens: ${message}\n`);
  process.exit(2);
}

function kebab(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function isPlainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

/**
 * Turn one token $value into CSS declarations (name: value pairs).
 * - primitives emit one declaration
 * - typography composites flatten into <name>-<kebab(subkey)>
 * - shadow composites compose into a box-shadow shorthand
 * `cssName` is the dash-joined custom-property base; `dotted` is the human token path.
 */
function declarationsFor(cssName, dotted, value, type, themeName) {
  if (Array.isArray(value)) {
    if (type === "shadow") {
      return [[cssName, value.map((s) => shadowShorthand(s, dotted, themeName)).join(", ")]];
    }
    fail(`theme "${themeName}": token "${dotted}" has array $value of unsupported type "${type ?? "?"}"`);
  }
  if (isPlainObject(value)) {
    if (type === "shadow") {
      return [[cssName, shadowShorthand(value, dotted, themeName)]];
    }
    const out = [];
    for (const [key, sub] of Object.entries(value)) {
      if (key.startsWith("$")) continue;
      if (isPlainObject(sub) || Array.isArray(sub)) {
        fail(`theme "${themeName}": token "${dotted}.${key}" must be a primitive $value sub-entry`);
      }
      out.push([`${cssName}-${kebab(key)}`, String(sub)]);
    }
    return out;
  }
  return [[cssName, String(value)]];
}

function shadowShorthand(shadow, name, themeName) {
  if (!isPlainObject(shadow)) {
    fail(`theme "${themeName}": token "${name}" shadow entry must be an object`);
  }
  const offsetX = shadow.offsetX ?? shadow.x;
  const offsetY = shadow.offsetY ?? shadow.y;
  const { blur, spread, color } = shadow;
  if (offsetX === undefined || offsetY === undefined || blur === undefined) {
    fail(`theme "${themeName}": token "${name}" shadow needs offsetX/offsetY/blur (got ${JSON.stringify(shadow)})`);
  }
  return [offsetX, offsetY, blur, spread ?? "0px", color ?? "transparent"].join(" ");
}

/**
 * Walk one theme section into [name, value] declaration pairs.
 * Group objects carry $type; token objects carry $value; anything else = input
 * error. One exception (contract groups, todo 19): a namespace folder (an
 * object whose children are ALL groups — e.g. motion holding easing/duration)
 * needs no $type of its own.
 */
function isNamespaceFolder(entry) {
  if (!isPlainObject(entry)) return false;
  if (Object.prototype.hasOwnProperty.call(entry, "$value")) return false;
  const children = Object.entries(entry).filter(([key]) => !key.startsWith("$"));
  return (
    children.length > 0 &&
    children.every(([, child]) => isPlainObject(child) && !Object.prototype.hasOwnProperty.call(child, "$value"))
  );
}

function collectTheme(themeName, theme) {
  const declarations = [];
  const walk = (node, pathParts) => {
    for (const [key, entry] of Object.entries(node)) {
      if (key.startsWith("$")) continue;
      const parts = [...pathParts, kebab(key)];
      const dotted = parts.join(".");
      const cssName = parts.join("-");
      if (!isPlainObject(entry)) {
        fail(`theme "${themeName}": token "${dotted}" must be an object with $value`);
      }
      if (Object.prototype.hasOwnProperty.call(entry, "$value")) {
        const type = entry.$type ?? node.$type ?? null;
        declarations.push(...declarationsFor(cssName, dotted, entry.$value, type, themeName));
      } else if (typeof entry.$type === "string" || isNamespaceFolder(entry)) {
        walk(entry, parts);
      } else {
        fail(`theme "${themeName}": token "${dotted}" missing $value`);
      }
    }
  };
  for (const [groupName, group] of Object.entries(theme)) {
    if (groupName.startsWith("$")) continue;
    if (!isPlainObject(group)) {
      fail(`theme "${themeName}": group "${groupName}" must be an object`);
    }
    if (typeof group.$type !== "string" && !isNamespaceFolder(group)) {
      fail(`theme "${themeName}": group "${groupName}" missing $type`);
    }
    walk(group, [kebab(groupName)]);
  }
  return declarations;
}

function buildCss(hash, themeDeclarations) {
  const lines = [
    generatedHeader(hash),
    "",
  ];
  for (const themeName of THEMES) {
    lines.push(`[data-theme="${themeName}"] {`);
    for (const [name, value] of themeDeclarations[themeName]) {
      lines.push(`  --${name}: ${value};`);
    }
    lines.push("}");
    lines.push("");
  }
  return lines.join("\n");
}

/**
 * utilities.css: ONLY matrix rules, same GENERATED header, values are either
 * var(--…)-based or non-color literals (0, px/rem, %, vw/vh, unitless, keywords).
 */
function buildUtilitiesCss(hash, matrix) {
  const lines = [
    generatedHeader(hash),
    "",
  ];
  for (const { name, decls } of matrix) {
    const selector = name.startsWith("[") ? name : `.${name}`;
    lines.push(`${selector} {`);
    for (const [prop, value] of decls) {
      lines.push(`  ${prop}: ${value};`);
    }
    lines.push("}");
    lines.push("");
  }
  return lines.join("\n");
}

/**
 * tokens.contract.md (todo 20): the generated values table over the SAME tree
 * this script writes to tokens.json (single source of truth — never
 * hand-maintained values). Rows are the token paths of the light ∪ dark theme
 * sections in codepoint order; a composite $value renders as compact JSON and
 * table-significant characters (|, newlines) are escaped. rules/contract-doc-sync.mjs
 * regenerates this content in-memory and byte-diffs it against the artifact
 * and against the SKILL.md <!-- contract:begin -->/<!-- contract:end --> embed.
 */
function buildContract(tree) {
  const rows = new Map(); // token path -> { light, dark } rendered cells
  for (const themeName of THEMES) {
    const section = isPlainObject(tree[themeName]) ? tree[themeName] : {};
    collectContractRows(section, "", (path, cell) => {
      const row = rows.get(path) ?? { light: "", dark: "" };
      row[themeName] = cell;
      rows.set(path, row);
    });
  }
  const lines = [
    "<!-- GENERATED by gen-tokens.mjs --contract — do not edit; source: tokens.json -->",
    "| token | light | dark |",
    "| --- | --- | --- |",
  ];
  for (const path of [...rows.keys()].sort()) {
    const row = rows.get(path);
    lines.push(`| ${path} | ${row.light} | ${row.dark} |`);
  }
  return `${lines.join("\n")}\n`;
}

/** Leaf = any object carrying $value (namespace folders and groups recurse). */
function collectContractRows(node, prefix, emit) {
  for (const [key, entry] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (!isPlainObject(entry)) continue;
    const path = prefix === "" ? key : `${prefix}.${key}`;
    if (Object.prototype.hasOwnProperty.call(entry, "$value")) {
      emit(path, contractCell(entry.$value));
    } else {
      collectContractRows(entry, path, emit);
    }
  }
}

function contractCell(value) {
  const text = isPlainObject(value) || Array.isArray(value) ? JSON.stringify(value) : String(value);
  return text.replaceAll("|", "\\|").replaceAll("\r", "").replaceAll("\n", "\\n");
}

const usage = "gen-tokens.mjs [design-root] | --list | --contract [design-root] [contract-out]";

function main(argv) {
  // Unknown flags ALWAYS exit 2 — checked before any other behavior (even --list).
  const flags = argv.filter((a) => a.startsWith("--"));
  const unknown = flags.filter((f) => f !== "--list" && f !== "--contract");
  if (unknown.length > 0) {
    fail(`unknown flag "${unknown[0]}" — usage: ${usage}`);
  }
  const positional = argv.filter((a) => !a.startsWith("--"));
  const contract = flags.includes("--contract");
  if (flags.includes("--list")) {
    if (contract) {
      fail(`--list and --contract cannot combine — usage: ${usage}`);
    }
    if (positional.length > 0) {
      fail(`usage: ${usage} (got ${positional.length} positional args)`);
    }
    const matrix = buildMatrix();
    process.stdout.write(`${matrix.map((e) => e.name).join("\n")}\n`);
    return 0;
  }
  if (contract ? positional.length > 2 : positional.length > 1) {
    fail(`usage: ${usage} (got ${positional.length} positional args)`);
  }

  const root = resolve(positional[0] ?? "./design");
  const tokensPath = join(root, "tokens.json");
  let raw;
  try {
    raw = readFileSync(tokensPath);
  } catch {
    fail(`cannot read ${tokensPath}`);
  }
  // Windows-safe normalization: parsing must not depend on \r line endings.
  const normalized = raw.toString("utf8").replace(/\r/g, "");
  let tokens;
  try {
    tokens = JSON.parse(normalized);
  } catch (err) {
    fail(`invalid JSON in ${tokensPath}: ${err.message}`);
  }
  if (!isPlainObject(tokens)) {
    fail(`invalid tokens in ${tokensPath}: root must be an object`);
  }
  for (const themeName of THEMES) {
    if (!isPlainObject(tokens[themeName])) {
      fail(`invalid tokens in ${tokensPath}: missing "${themeName}" theme section`);
    }
  }

  // Contract groups (todo 19) are written into tokens.json on every run; the
  // deterministic serialization (stable key order) is the hash input, so the
  // tokens-hash in the generated banners covers the contract groups too.
  // JSON.stringify output never contains raw \r, so the hash is exactly what
  // validate.mjs recomputes over the file bytes (its \r strip is a no-op here).
  // Declarations are collected from the SAME tree that is serialized (and not
  // from the raw parse) so the CSS output is identical on the first run and on
  // every re-run — the contract-group vars appear either way.
  const withGroups = withContractGroups(tokens);
  const serialized = `${JSON.stringify(withGroups, null, 2)}\n`;
  writeFileSync(tokensPath, serialized, "utf8");
  const hash = createHash("sha256").update(serialized, "utf8").digest("hex");
  const themeDeclarations = {};
  for (const themeName of THEMES) {
    themeDeclarations[themeName] = collectTheme(themeName, withGroups[themeName]);
  }
  const matrix = buildMatrix();

  const outPath = join(root, "design-system.css");
  writeFileSync(outPath, buildCss(hash, themeDeclarations), "utf8");
  process.stdout.write(`wrote ${outPath}\n`);
  const utilitiesPath = join(root, "utilities.css");
  writeFileSync(utilitiesPath, buildUtilitiesCss(hash, matrix), "utf8");
  process.stdout.write(`wrote ${utilitiesPath}\n`);
  if (contract) {
    // The table derives from the SAME tree serialized above into tokens.json.
    const contractOut = positional[1] ? resolve(positional[1]) : join(root, "tokens.contract.md");
    writeFileSync(contractOut, buildContract(withGroups), "utf8");
    process.stdout.write(`wrote ${contractOut}\n`);
  }
  return 0;
}

process.exit(main(process.argv.slice(2)));
